  Future<ApiCallResponse> _cargar() async {
    final response = await WSInventariosGroup.conteosCall
        .call(usuario: FFAppState().idUsuario);
    checkConteoResponse(response);
    final rows = conteoRows(response.jsonBody)
        .map((row) => {
              'docNum': conteoText(row, ['DocNum', 'Referencia', 'BaseEntry']),
              'docEntry': conteoText(row, ['BaseEntry']),
              'docDate': conteoText(row, ['Fecha', 'DocDate']),
              'almacen': conteoText(row, ['Almacen', 'AlmacenD', 'WhsCode']),
              'referencia': conteoText(row, ['Referencia', 'DocNum']),
            })
        .toList();
    return ApiCallResponse(
        {'valores': rows}, response.headers, response.statusCode);
  }

