  Future<void> _crear(dynamic conteo) async {
    if (_creando) return;
    final baseEntry = conteoText(conteo, ['BaseEntry']);
    if (baseEntry.isEmpty) return;
    setState(() => _creando = true);
    try {
      final response = await WSInventariosGroup.documentoNuevoCall.call(
        documento: '4',
        usuario: FFAppState().idUsuario,
        baseType: '1000',
        baseEntry: baseEntry,
      );
      checkConteoResponse(response);
      final docCode = conteoText(response.jsonBody, ['DocumentoInterno']);
      if (docCode.isEmpty) {
        throw StateError(
            'La API no devolvió DocumentoInterno. Revisa documentos abiertos antes de volver a crear el conteo.');
      }
      if (!mounted) return;
      FFAppState().update(() {
        FFAppState().TipoDoc = 4;
        FFAppState().NombrePrincipal = 'Documentos abiertos Conteos';
      });
      context.goNamed(PrincipalWidget.routeName);
    } catch (error) {
      if (mounted) {
        await showDialog<void>(
            context: context,
            builder: (context) => AlertDialog(
                  title: const Text('No se pudo crear el conteo'),
                  content: Text(conteoErrorText(error)),
                  actions: [
                    TextButton(
                        onPressed: () => Navigator.pop(context),
                        child: const Text('Entendido'))
                  ],
                ));
      }
    } finally {
      if (mounted) setState(() => _creando = false);
    }
  }

